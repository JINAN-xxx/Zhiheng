import hashlib
import importlib
import re
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest
import yaml

from plugins.core.lifecycle.script import PluginLifecycleScriptHelper

BACKEND_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = BACKEND_ROOT / 'scripts' / 'build_platform_sql.py'
PLUGIN_IDS = ('ai', 'agent_extension')
FIXTURE_MIGRATION_COUNT = 6


def generator() -> ModuleType:
    assert SCRIPT.is_file(), 'The platform SQL generator must exist'
    return importlib.import_module('scripts.build_platform_sql')


@pytest.fixture
def source_root(tmp_path: Path) -> Path:
    (tmp_path / 'sql').mkdir()
    (tmp_path / 'sql' / 'ruoyi-fastapi-pg.sql').write_text(
        'create table sys_plugin_migration (plugin_id text);\n', encoding='utf-8'
    )
    for plugin_id in PLUGIN_IDS:
        plugin_root = tmp_path / 'plugins' / plugin_id
        sources = {
            'migrations/postgresql/002_second.sql': b"-- comment\r\nselect 'semi;colon';\r\nselect 2;\r\n",
            'migrations/mysql/001_first.sql': b'select MYSQL_ONLY_MIGRATION;',
            'migrations/001_common.sql': b'select COMMON_MIGRATION;',
            'migrations/postgresql/001_first.sql': b'select PG_FIRST;',
            'seeds/mysql/data.sql': b'select MYSQL_ONLY_SEED;',
            'seeds/postgresql/data.sql': b'select PG_SEED;',
        }
        for relative_path, content in sources.items():
            path = plugin_root / relative_path
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        (plugin_root / 'plugin.yaml').write_text(
            yaml.safe_dump(
                {
                    'id': plugin_id,
                    'version': '1.2.3',
                    'backend': {
                        'migrations': [path for path in sources if path.startswith('migrations/')],
                        'seeds': [path for path in sources if path.startswith('seeds/')],
                    },
                }
            ),
            encoding='utf-8',
        )
    return tmp_path


def test_filters_mysql_and_keeps_common_postgresql_scripts(source_root: Path) -> None:
    sql = generator().render_platform_sql(source_root)

    assert 'MYSQL_ONLY_MIGRATION' not in sql
    assert 'MYSQL_ONLY_SEED' not in sql
    assert sql.count('select COMMON_MIGRATION;') == len(PLUGIN_IDS)
    assert sql.count('select PG_FIRST;') == len(PLUGIN_IDS)
    assert sql.count('select PG_SEED;') == len(PLUGIN_IDS)


def test_preserves_manifest_order_and_plugin_dependency_order(source_root: Path) -> None:
    sql = generator().render_platform_sql(source_root)
    paths = [
        'sql/ruoyi-fastapi-pg.sql',
        'plugins/ai/migrations/postgresql/002_second.sql',
        'plugins/ai/migrations/001_common.sql',
        'plugins/ai/migrations/postgresql/001_first.sql',
        'plugins/ai/seeds/postgresql/data.sql',
        'plugins/agent_extension/migrations/postgresql/002_second.sql',
        'plugins/agent_extension/migrations/001_common.sql',
        'plugins/agent_extension/migrations/postgresql/001_first.sql',
        'plugins/agent_extension/seeds/postgresql/data.sql',
    ]

    positions = [sql.index(f'-- Source: {path}\n') for path in paths]
    assert positions == sorted(positions)


def test_history_uses_raw_byte_checksum_version_and_runtime_statement_count(source_root: Path) -> None:
    sql = generator().render_platform_sql(source_root)
    source_path = source_root / 'plugins/ai/migrations/postgresql/002_second.sql'
    checksum = hashlib.sha256(source_path.read_bytes()).hexdigest()
    assert checksum != hashlib.sha256(source_path.read_text().encode()).hexdigest()

    assert f"'ai', 'migrations/postgresql/002_second.sql', '{checksum}', '1.2.3', 2, 'success'" in sql
    assert 'error_message, attempt_count, started_time, finished_time, create_time, update_time' in sql
    assert (
        sql.count('NULL, 1, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP')
        == FIXTURE_MIGRATION_COUNT
    )
    assert sql.index("select 'semi;colon';") < sql.index('INSERT INTO sys_plugin_migration')
    assert not re.search(r"VALUES\s*\([^;]*'seeds/", sql, re.IGNORECASE)


def test_rejects_nonempty_public_schema_before_any_destructive_sql() -> None:
    sql = generator().render_platform_sql(BACKEND_ROOT)

    assert sql.startswith('-- Generated by scripts/build_platform_sql.py')
    assert not re.search(r'^\\', sql, re.MULTILINE)
    assert 'pg_catalog.pg_depend' in sql
    assert 'pg_catalog.pg_namespace' in sql
    assert "nspname = 'public'" in sql
    assert sql.index("RAISE EXCEPTION 'platform-pg.sql requires an empty public schema'") < sql.index('drop table')
    assert 'SET search_path TO public, pg_catalog;' in sql
    assert not re.search(r'^\s*(?:BEGIN|COMMIT|START TRANSACTION)\s*;', sql, re.IGNORECASE | re.MULTILINE)


def test_combines_every_declared_postgresql_source_without_installing_plugins() -> None:
    sql = generator().render_platform_sql(BACKEND_ROOT)
    base = (BACKEND_ROOT / 'sql/ruoyi-fastapi-pg.sql').read_text(encoding='utf-8')
    assert base in sql
    expected_migrations = 0
    for plugin_id in PLUGIN_IDS:
        plugin_root = BACKEND_ROOT / 'plugins' / plugin_id
        manifest = yaml.safe_load((plugin_root / 'plugin.yaml').read_text(encoding='utf-8'))
        for kind in ('migrations', 'seeds'):
            for relative_path in manifest['backend'].get(kind, []):
                if '/mysql/' in relative_path:
                    assert f'-- Source: plugins/{plugin_id}/{relative_path}\n' not in sql
                    continue
                path = plugin_root / relative_path
                content = path.read_text(encoding='utf-8')
                assert content in sql
                if kind == 'migrations':
                    expected_migrations += 1
                    count = len(PluginLifecycleScriptHelper.split_sql_statements(content))
                    checksum = hashlib.sha256(path.read_bytes()).hexdigest()
                    assert (
                        f"'{plugin_id}', '{relative_path}', '{checksum}', '{manifest['version']}', {count}, 'success'"
                    ) in sql

    assert sql.count('INSERT INTO sys_plugin_migration (') == expected_migrations > 0
    assert not re.search(r'insert\s+into\s+sys_plugin\b', sql, re.IGNORECASE)


def test_generation_is_deterministic_and_tracks_source_changes(source_root: Path) -> None:
    initial = generator().render_platform_sql(source_root)
    assert generator().render_platform_sql(source_root) == initial
    path = source_root / 'plugins/ai/migrations/postgresql/001_first.sql'
    path.write_text('select CHANGED;\n', encoding='utf-8')

    assert generator().render_platform_sql(source_root) != initial


def test_check_detects_missing_and_stale_output_without_writing(
    source_root: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    module = generator()
    output = source_root / 'sql/platform-pg.sql'
    assert module.main(['--check'], backend_root=source_root) == 1
    assert not output.exists()
    assert module.main([], backend_root=source_root) == 0
    original = output.read_bytes()
    assert module.main(['--check'], backend_root=source_root) == 0
    (source_root / 'plugins/ai/seeds/postgresql/data.sql').write_text('select CHANGED;\n', encoding='utf-8')

    assert module.main(['--check'], backend_root=source_root) == 1
    assert output.read_bytes() == original
    assert 'build_platform_sql.py' in capsys.readouterr().err


def test_output_option_writes_requested_artifact(source_root: Path) -> None:
    module = generator()
    output = source_root / 'custom.sql'
    assert module.main(['--output', str(output)], backend_root=source_root) == 0
    assert output.read_text(encoding='utf-8') == module.render_platform_sql(source_root)
    assert not (source_root / 'sql/platform-pg.sql').exists()


@pytest.mark.parametrize(
    'invalid_path', ['migrations/postgresql/missing.sql', '../outside.sql', 'migrations/custom.py']
)
def test_refuses_unrepresentable_manifest_scripts(source_root: Path, invalid_path: str) -> None:
    path = source_root / 'plugins/ai/plugin.yaml'
    manifest = yaml.safe_load(path.read_text(encoding='utf-8'))
    manifest['backend']['migrations'].append(invalid_path)
    path.write_text(yaml.safe_dump(manifest), encoding='utf-8')

    with pytest.raises((ValueError, RuntimeError, FileNotFoundError)):
        generator().render_platform_sql(source_root)


def test_committed_sql_is_current_when_script_runs_outside_backend(tmp_path: Path) -> None:
    result = subprocess.run(
        [sys.executable, str(SCRIPT), '--check'], cwd=tmp_path, capture_output=True, text=True, check=False
    )

    assert result.returncode == 0, result.stderr
