def upgrade() -> None:
    connection = op.get_bind()
    for row in connection.execute(sa.text('SELECT id, permissions FROM identity_roles FOR UPDATE')).mappings():
        original = row['permissions']
        values = json.loads(original) if isinstance(original, str) else list(original or [])
        converted = set()
        for code in values:
            if code in LEGACY:
                converted.update(LEGACY[code])
            elif code in CANONICAL:
                converted.add(code)
        result = sorted(converted)
        if result != values:
            connection.execute(
                sa.text(
                    'UPDATE identity_roles SET permissions=CAST(:permissions AS json), version=version+1, updated_at=now() WHERE id=:id'
                ),
                {'id': row['id'], 'permissions': json.dumps(result)},
            )


def downgrade() -> None:
    rows = op.get_bind().execute(sa.text('SELECT permissions FROM identity_roles')).scalars()
    for value in rows:
        codes = json.loads(value) if isinstance(value, str) else (value or [])
        if any(code.endswith(':enabled') for code in codes):
            raise RuntimeError('Restore a reviewed role-permission backup before downgrading operation-level grants')
