#!/usr/bin/env python3
"""Generate the fresh-install PostgreSQL SQL from the platform and plugin sources.

Run from any directory with ``python scripts/build_platform_sql.py``; use
``--check`` in CI to detect an artifact that needs regeneration. No database
connection or application configuration is needed.
"""

import argparse
import hashlib
import sys
from pathlib import Path

import yaml

BACKEND_ROOT = Path(__file__).resolve().parents[1]
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))

from plugins.core.lifecycle.script import PluginLifecycleScriptHelper  # noqa: E402

# agent_extension depends on ai. Preserve each manifest's own declaration order.
PLATFORM_PLUGINS = ('ai', 'agent_extension')

SQL_HEADER = """-- Generated by scripts/build_platform_sql.py; do not edit this file directly.
-- Sources: sql/zhiheng-fastapi-pg.sql and the bundled plugin.yaml declarations.
-- Fresh installations only: public must contain no objects.
-- Execute in ONE transaction, with rollback on any error. For psql use:
-- psql -v ON_ERROR_STOP=1 --single-transaction -f sql/platform-pg.sql
-- No transaction boundary is included so deployment can append its bootstrap marker.
-- Plugin menus, permissions, jobs and installation state are synchronized at startup.

DO $platform_guard$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM pg_catalog.pg_depend AS dependency
        JOIN pg_catalog.pg_namespace AS namespace
          ON dependency.refobjid = namespace.oid
         AND dependency.refclassid = 'pg_catalog.pg_namespace'::pg_catalog.regclass
        WHERE namespace.nspname = 'public'
    ) THEN
        RAISE EXCEPTION 'platform-pg.sql requires an empty public schema';
    END IF;
END;
$platform_guard$;

SET search_path TO public, pg_catalog;

"""


def _sql_literal(value: str) -> str:
    """Quote manifest metadata as a PostgreSQL string literal."""
    return "'" + value.replace("'", "''") + "'"


def _source_section(path: Path, backend_root: Path) -> str:
    """Retain source SQL intact, including functions that the runner cannot split."""
    content = path.read_text(encoding='utf-8')
    return f'-- Source: {path.relative_to(backend_root).as_posix()}\n{content}\n'


def render_platform_sql(backend_root: Path = BACKEND_ROOT) -> str:
    """Combine platform SQL and PostgreSQL plugin scripts with migration history."""
    backend_root = backend_root.resolve()
    sections = [SQL_HEADER, _source_section(backend_root / 'sql/zhiheng-fastapi-pg.sql', backend_root)]
    for plugin_id in PLATFORM_PLUGINS:
        plugin_root = backend_root / 'plugins' / plugin_id
        manifest = yaml.safe_load((plugin_root / 'plugin.yaml').read_text(encoding='utf-8'))
        if manifest['id'] != plugin_id:
            raise ValueError(f'Plugin directory and manifest id differ: {plugin_id}')

        for kind in ('migrations', 'seeds'):
            paths = PluginLifecycleScriptHelper.filter_current_database_paths(
                manifest['backend'].get(kind, []), root_dir=kind, database_type='postgresql'
            )
            for relative_path in paths:
                if Path(relative_path).suffix != '.sql':
                    raise ValueError(f'Cannot include non-SQL {kind} in platform-pg.sql: {relative_path}')
                path = PluginLifecycleScriptHelper.resolve_file(
                    plugin_root, relative_path, supported_suffixes={'.sql'}, label=kind
                )
                sections.append(_source_section(path, backend_root))
                if kind == 'seeds':
                    continue

                checksum = hashlib.sha256(path.read_bytes()).hexdigest()
                statement_count = len(
                    PluginLifecycleScriptHelper.split_sql_statements(path.read_text(encoding='utf-8'))
                )
                metadata = ', '.join(
                    _sql_literal(value) for value in (plugin_id, relative_path, checksum, str(manifest['version']))
                )
                sections.append(
                    'INSERT INTO sys_plugin_migration (\n'
                    '    plugin_id, migration_path, migration_checksum, version, statement_count, status,\n'
                    '    error_message, attempt_count, started_time, finished_time, create_time, update_time\n'
                    ') VALUES (\n'
                    f"    {metadata}, {statement_count}, 'success',\n"
                    '    NULL, 1, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP\n'
                    ');\n'
                )
    return '\n'.join(sections)


def main(argv: list[str] | None = None, *, backend_root: Path = BACKEND_ROOT) -> int:
    """Write the generated artifact, or compare it without modifying any files."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the generated SQL is missing or stale')
    parser.add_argument('--output', type=Path, help='Output path (default: backend/sql/platform-pg.sql)')
    args = parser.parse_args(argv)
    output = args.output or backend_root / 'sql/platform-pg.sql'
    try:
        content = render_platform_sql(backend_root).encode('utf-8')
        if args.check:
            if not output.is_file() or output.read_bytes() != content:
                print(
                    f'{output} is missing or stale; run scripts/build_platform_sql.py to regenerate it.',
                    file=sys.stderr,
                )
                return 1
            print(f'{output} is up to date.')
            return 0
        output.write_bytes(content)
    except (OSError, RuntimeError, ValueError, KeyError, TypeError, yaml.YAMLError) as exc:
        print(f'Could not generate platform SQL: {exc}', file=sys.stderr)
        return 1
    print(f'Generated {output}.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
